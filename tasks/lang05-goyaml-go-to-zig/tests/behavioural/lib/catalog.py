def module_families() -> dict[str, tuple[str, ...]]:
    """Module id -> the frozen families it grades.  Empty tuples omitted."""
    return {m["id"]: tuple(m["families"]) for m in MODULES if m["families"]}


def family_module() -> dict[str, str]:
    """Family -> the one module that grades it, frozen and fresh alike.

    For reporting: given a family name from a case, which module owns it.  Not for
    sharding -- see `frozen_family_module`.
    """
    out: dict[str, str] = {}
    for module in MODULES:
        for family in module["families"]:
            out[family] = module["id"]
    return out


def frozen_family_module() -> dict[str, str]:
    """Frozen family -> the frozen module that shards and grades it.

    Restricted to `kind == "frozen"`, which is the whole point of it existing
    beside `family_module`.  The fresh module claims two families as well, and
    those cases do not exist until grading time: sharding the frozen cases by
    every claimed family would cut an empty shard for `unseen-inputs`, and
    `shard_cases` rightly refuses an empty shard -- so the image build would fail
    with a message about a module whose cases are not supposed to be in there.
    """
    return {
        family: module["id"]
        for module in MODULES if module["kind"] == "frozen"
        for family in module["families"]
    }


def check_modules() -> list[str]:
    """Everything that would make the module table disagree with the budgets."""
    problems: list[str] = []
    ids = [m["id"] for m in MODULES]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        problems.append(f"duplicate module ids: {dupes}")

    # Every family has exactly one module, and no module claims a family that
    # does not exist.  Without this a family could be graded twice at full weight,
    # or silently not at all.
    claimed: dict[str, list[str]] = {}
    for module in MODULES:
        for family in module["families"]:
            claimed.setdefault(family, []).append(module["id"])
    for family, owners in sorted(claimed.items()):
        if len(owners) > 1:
            problems.append(f"family {family!r} is claimed by {owners}")
    for family in sorted(set(FAMILY_BUDGETS) - set(claimed)):
        problems.append(
            f"family {family!r} has a budget but no module grades it")
    for family in sorted(set(FRESH_BUDGETS) - set(claimed)):
        problems.append(
            f"fresh family {family!r} has a budget but no module grades it")
    known = set(FAMILY_BUDGETS) | set(FRESH_BUDGETS)
    for family in sorted(set(claimed) - known):
        problems.append(
            f"module {claimed[family][0]!r} grades family {family!r}, which has "
            f"no budget")

    # A family's budget table has to match the kind of the module that claims it.
    # A frozen family claimed by the fresh module would be graded against cases
    # generated at run time, which hold none of its own; a fresh family claimed by
    # a frozen module would be sharded out of the frozen cases, which hold none of
    # its own either -- and an empty shard aborts the image build.
    for module in MODULES:
        table, other = ((FRESH_BUDGETS, FAMILY_BUDGETS) if module["kind"] == "fresh"
                        else (FAMILY_BUDGETS, FRESH_BUDGETS))
        for family in module["families"]:
            if family not in table and family in other:
                problems.append(
                    f"module {module['id']!r} is kind {module['kind']!r} and claims "
                    f"family {family!r}, whose budget is in the other table; the "
                    f"cases it grades are generated at the wrong time")

    # Each weight equals what it claims to be made of.  This is the check that
    # makes the literal weights above safe to read without executing them.
    fixed = {
        "build": sum(c[2] for c in BUILD_CASES),
        "documents": DOCUMENT_BUDGET,
        "protocol": PROTOCOL_BUDGET + sum(c[2] for c in PROBE_CASES),
        "provenance": sum(c[2] for c in PROVENANCE_CASES),
    }
    for module in MODULES:
        kind = module["kind"]
        if kind in fixed:
            want = fixed[kind]
        else:
            table = FRESH_BUDGETS if kind == "fresh" else FAMILY_BUDGETS
            want = sum(table.get(f, 0.0) for f in module["families"])
        if abs(want - float(module["weight"])) > 1e-6:
            problems.append(
                f"module {module['id']!r} declares weight {module['weight']}, but "
                f"the budgets it grades sum to {want}")

    for kind in ("build", "fresh", "documents", "protocol", "provenance"):
        if sum(1 for m in MODULES if m["kind"] == kind) != 1:
            problems.append(f"expected exactly one module of kind {kind!r}")
    # Nothing here demands that a module be declared mandatory, and nothing needs
    # to: a suite where every scored check must pass has no way to credit a
    # submission that never built.  A tree without an executable fails `build` and
    # every module that reads it, and one failing scored check pays the stage
    # nothing.  The inverse is what is checked, above: every declared weight must
    # equal the budgets it grades, so a module cannot quietly stop mattering.
    for module in MODULES:
        if "required" in module:
            problems.append(
                f"module {module['id']!r} declares `required`, which is retired; "
                f"swerefactor/config.py rejects a stage-2 module that carries it")
    return problems
