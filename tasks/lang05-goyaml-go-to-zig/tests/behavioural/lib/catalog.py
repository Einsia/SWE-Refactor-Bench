#!/usr/bin/env python3
"""What lang05 measures, in one inventory.

The cases themselves are generated by `generator`, because only Go can harvest
go-yaml's own test files and only the reference can say what the answers are.
What this module owns is everything they do not: how much each family is
worth, the protocol cases, the structural cases and the audit gates.

The weighting is the part worth reading.  The mix is deliberately lopsided --
`compose` has 2,484 cases because crossing six operations with a few hundred
composed documents is cheap, and `roundtrip` has 38 because there are only so
many shapes whose re-emission is interesting.  Grading per case would make
composed documents worth 65 times the roundtrip family, which is not what a
reader of this task would say those two things are worth to it.  So each family
gets a budget, and its cases divide that budget equally.  A family's importance
is then a declared number in this file rather than an accident of how many cases
it was cheap to generate.
"""

