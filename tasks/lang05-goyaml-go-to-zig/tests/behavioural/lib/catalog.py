# The distinct problem texts instruction.md claims the frozen cases reach.  A
# generator edit that dropped half of that family would still produce cases of the
# right size, and the document would then be wrong about the task.  The figure is
# not written out in this comment: it is the constant below, and a second spelling
# beside it is a second thing to update.
MIN_ERROR_TEXTS = 42

# What "distinct problem text" counts.  The rule has to live in one place because
# two things depend on it: freeze.py derives the figure from the frozen
# expectations, and `check_catalog` compares it against the floor above -- and
# instruction.md states it to the agent as a fact about the graded cases.
#
# The envelope is `yaml: ` then, when a line is known, `line N: `, then the
# problem text.  Only the problem text is counted, which is the distinction the
# document draws: `did not find expected key` reported at line 1 and at line 2 is
# one problem text seen twice, not two.  Counting whole messages gives 56 for the
# same inputs, and a figure that changes with the line numbers in them is
# not a fact about coverage.
PROBLEM_TEXT_ENVELOPE = re.compile(r"^yaml: (?:line \d+: )?")


def problem_text(message: str) -> str:
    """The problem text inside one go-yaml error message."""
    return PROBLEM_TEXT_ENVELOPE.sub("", message)


#: Where a graded error string can appear inside a successful result.  `stream`
#: and `emit_stream` report a failure alongside the output they managed, and
#: `roundtrip` reports one for each of its two later stages, so these four fields
#: hold error text that is compared byte for byte and never appears in a
#: top-level `error` object.  Counting only the top level said 41 where the
#: expectations hold 42, and the missing one was `expected STREAM-START` -- the
#: text instruction.md documents by name, which no case could have reached
#: through the top level, because an empty stream is a successful emit_stream.
RESULT_ERROR_FIELDS = ("error", "reparse_error", "reemit_error")


def distinct_problem_texts(expected_path: Path) -> set[str]:
    """Every distinct problem text in a frozen expectation file.

    Both places one can appear: the `error` object of a failed request, and the
    error fields of a result that partly succeeded.  Every one of them is graded,
    so the count the task publishes has to span both.

    Streams the file rather than loading it: the frozen expectations are ~3 MB and
    the fresh ones are generated per run.  The recursion limit is raised because
    the generator deliberately emits documents nested 10,000 deep, and the stdlib
    JSON decoder recurses on nested arrays.
    """
    previous = sys.getrecursionlimit()
    sys.setrecursionlimit(max(previous, 300_000))
    try:
        out: set[str] = set()
        with expected_path.open("rb") as fh:
            for raw in fh:
                raw = raw.strip()
                if not raw:
                    continue
                try:
                    payload = json.loads(raw)
                except ValueError:
                    continue
                error = payload.get("error")
                if isinstance(error, dict) and error.get("message"):
                    out.add(problem_text(error["message"]))
                result = payload.get("result")
                if isinstance(result, dict):
                    for field in RESULT_ERROR_FIELDS:
                        text = result.get(field)
                        if isinstance(text, str) and text:
                            out.add(problem_text(text))
        return out
    finally:
        sys.setrecursionlimit(previous)


def summary(counts: dict[str, int], fresh: dict[str, int],
            documents: int, protocol: int) -> dict:
    """The inventory, as a dict, for the report and for `--check`."""

    def block(table: dict[str, float], sizes: dict[str, int]) -> dict:
        weights = family_weights(sizes, table)
        return {
            family: {
                "cases": sizes[family],
                "budget": round(table.get(family, 0.0), 3),
                "per_case_weight": round(weights.get(family, 0.0), 6),
            }
            for family in sorted(sizes)
        }

    frozen_budget = sum(FAMILY_BUDGETS.get(f, 0.0) for f in counts if counts[f] > 0)
    fresh_budget = sum(FRESH_BUDGETS.get(f, 0.0) for f in fresh if fresh[f] > 0)
    total = sum(m["weight"] for m in MODULES)
    return {
        "frozen_cases": sum(counts.values()),
        "frozen_families": len(counts),
        "frozen_budget": round(frozen_budget, 3),
        "fresh_cases": sum(fresh.values()),
        "fresh_budget": round(fresh_budget, 3),
        "document_cases": documents,
        "document_budget": DOCUMENT_BUDGET,
        "protocol_cases": protocol,
        "protocol_budget": PROTOCOL_BUDGET,
        "total_behavioural_budget": round(total, 3),
        # The share each source carries, because the ratios are the design and a
        # reader should not have to add up 17 numbers to see them.
        "budget_share": {
            "frozen": round(frozen_budget / total, 4) if total else 0.0,
            "fresh": round(fresh_budget / total, 4) if total else 0.0,
            "documents": round(DOCUMENT_BUDGET / total, 4) if total else 0.0,
            "protocol": round(PROTOCOL_BUDGET / total, 4) if total else 0.0,
        },
        "families": block(FAMILY_BUDGETS, counts),
        "fresh_families": block(FRESH_BUDGETS, fresh),
        "build_cases": len(BUILD_CASES),
        "build_weight": round(sum(c[2] for c in BUILD_CASES), 3),
        "probe_cases": len(PROBE_CASES),
        "probe_weight": round(sum(c[2] for c in PROBE_CASES), 3),
        "provenance_cases": len(PROVENANCE_CASES),
        # The denominator the runner actually divides by: every module's weight,
        # normalised.  A reader comparing this against suite.toml is comparing the
        # two numbers that decide the score.
        "modules": len(MODULES),
        "module_weight_total": round(sum(m["weight"] for m in MODULES), 3),
        "module_share": {
            m["id"]: round(m["weight"] / sum(x["weight"] for x in MODULES), 4)
            for m in MODULES
        },
        "unknown_families": unknown_families(counts),
        "missing_families": missing_families(counts),
        "unknown_fresh_families": unknown_families(fresh, FRESH_BUDGETS),
        "missing_fresh_families": missing_families(fresh, FRESH_BUDGETS),
    }


def check_catalog(counts: dict[str, int], fresh: dict[str, int],
                  documents: int, protocol: int,
                  error_texts: int | None = None) -> list[str]:
    """Everything that would make this inventory wrong.  Empty means sound."""
    problems: list[str] = []
    total = sum(counts.values())
    if total < MIN_FROZEN_CASES:
        problems.append(
            f"the frozen shards hold {total} cases, expected at least "
            f"{MIN_FROZEN_CASES}")
    if sum(fresh.values()) < MIN_FRESH_CASES:
        problems.append(
            f"the fresh families hold {sum(fresh.values())} cases, expected at "
            f"least {MIN_FRESH_CASES}")
    if documents < MIN_DOCUMENT_CASES:
        problems.append(
            f"{documents} document cases, expected at least {MIN_DOCUMENT_CASES}")
    if protocol < MIN_PROTOCOL_CASES:
        problems.append(
            f"{protocol} protocol cases, expected at least {MIN_PROTOCOL_CASES}")
    if len(BUILD_CASES) < MIN_BUILD_CASES:
        problems.append(
            f"{len(BUILD_CASES)} build cases, expected at least {MIN_BUILD_CASES}")
    if len(PROBE_CASES) < MIN_PROBE_CASES:
        problems.append(
            f"{len(PROBE_CASES)} probe cases, expected at least {MIN_PROBE_CASES}")
    if len(PROVENANCE_CASES) < MIN_PROVENANCE_CASES:
        problems.append(
            f"{len(PROVENANCE_CASES)} provenance cases, expected at least "
            f"{MIN_PROVENANCE_CASES}")
    problems.extend(check_modules())
    if error_texts is not None and error_texts < MIN_ERROR_TEXTS:
        problems.append(
            f"the frozen expectations contain {error_texts} distinct YAML problem "
            f"texts; instruction.md claims {MIN_ERROR_TEXTS}. Count them with "
            f"catalog.distinct_problem_texts, which is the rule the document's "
            f"figure means.")
    for name in unknown_families(counts):
        problems.append(
            f"family {name!r} produced cases but has no declared budget "
            f"(graded at the mean, which is a guess)")
    for name in missing_families(counts):
        problems.append(
            f"family {name!r} has a budget but produced no cases: the generator "
            f"and this table disagree")
    for name in unknown_families(fresh, FRESH_BUDGETS):
        problems.append(f"fresh family {name!r} has no declared budget")
    for name in missing_families(fresh, FRESH_BUDGETS):
        problems.append(f"fresh family {name!r} has a budget but produced no cases")
    ids = ([c[0] for c in BUILD_CASES] + [c[0] for c in PROBE_CASES]
           + [c[0] for c in PROVENANCE_CASES])
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        problems.append(f"duplicate case ids: {dupes}")
    for table, name in ((BUILD_CASES, "build"), (PROBE_CASES, "probe"),
                        (PROVENANCE_CASES, "provenance")):
        for case in table:
            if not case[1]:
                problems.append(f"a {name} case declares an empty check name")
    # The protocol family must stay small relative to the whole.  It is the one
    # budget in this file that grades transport rather than YAML, and a later
    # edit that raised it would quietly turn envelope trivia into a significant
    # fraction of the score.
    # Against the whole behavioural denominator, which is the sum of the module
    # weights and not just the family budgets: the runner normalises by that, so a
    # share computed any other way is a share of something nobody divides by.
    frozen_budget = sum(FAMILY_BUDGETS.get(f, 0.0) for f in counts if counts[f] > 0)
    fresh_budget = sum(FRESH_BUDGETS.get(f, 0.0) for f in fresh if fresh[f] > 0)
    grand = sum(m["weight"] for m in MODULES)
    if grand and PROTOCOL_BUDGET > 0.03 * grand:
        problems.append(
            f"the protocol family carries {PROTOCOL_BUDGET:.1f} of {grand:.1f} "
            f"behavioural points; it grades an envelope, not YAML")
    # And the fresh families must stay significant, for the opposite reason: they
    # are the only term a submission cannot pass by memorising the image.
    if grand and fresh_budget < 0.10 * grand:
        problems.append(
            f"the fresh families carry {fresh_budget:.1f} of {grand:.1f} "
            f"behavioural points; they are the anti-memorisation term and should "
            f"be worth more")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cases", type=Path, help="cases.json from generator")
    ap.add_argument("--fresh", type=Path, help="fresh-cases.json from generator")
    ap.add_argument("--documents", type=Path, help="document-manifest.json")
    ap.add_argument("--protocol", type=Path, help="protocol-cases.json")
    ap.add_argument("--error-texts", type=int, default=None,
                    help="distinct YAML problem texts in the frozen expectations")
    ap.add_argument("--check", action="store_true", help="exit non-zero on drift")
    ap.add_argument("--out", type=Path, help="write the inventory here")
    args = ap.parse_args()

    counts: dict[str, int] = {}
    if args.cases and args.cases.is_file():
        counts = json.loads(args.cases.read_text())["families"]
    fresh: dict[str, int] = {}
    if args.fresh and args.fresh.is_file():
        fresh = json.loads(args.fresh.read_text())["families"]
    documents = 0
    if args.documents and args.documents.is_file():
        documents = len(json.loads(args.documents.read_text())["documents"])
    protocol = 0
    if args.protocol and args.protocol.is_file():
        protocol = json.loads(args.protocol.read_text())["count"]

    payload = summary(counts, fresh, documents, protocol)
    problems = (check_catalog(counts, fresh, documents, protocol, args.error_texts)
                if args.check else [])
    payload["problems"] = problems

    text = json.dumps(payload, indent=1, sort_keys=True)
    if args.out:
        args.out.write_text(text + "\n", encoding="utf-8")
    else:
        print(text)
    if problems:
        for problem in problems:
            print(f"catalog: {problem}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
