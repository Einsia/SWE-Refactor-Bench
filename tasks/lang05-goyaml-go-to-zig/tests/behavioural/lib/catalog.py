# The fresh cases, generated at grading time from a seed the submission has
# never seen and answered by the reference live in the container.  Two families,
# and they are the anti-memorisation term: a submission that embedded the 8,170
# frozen answers scores zero here.  Worth ~15% of the behavioural total, which is
# more than any single frozen family except `upstream`.
FRESH_BUDGETS: dict[str, float] = {
    "fresh-composed":    115.0,
    "fresh-mutated":     105.0,
}

# Twelve real-world files x six operations, graded on the whole-response digest.
# Worth a lot in aggregate: a port that handles every synthetic case and then
# diverges on a Kubernetes manifest has not been ported.  72 cases, so each
# carries 90/72 = 1.25 of the family's weight.
DOCUMENT_BUDGET = 90.0

# The protocol family: the transport rules, as cases.  Deliberately the smallest
# budget in the file.  It grades real contract -- the handshake, the two
# `emit_indent` argument errors, an unknown op, a malformed line, the empty-line
# rule, and response ordering -- but it is thirteen cases about an envelope, and
# this task is about YAML.  At 18 weight it sits just under `whitespace`, which
# is roughly the right ratio: getting the envelope wrong is a real defect, and it
# is a smaller defect than getting tabs wrong.
PROTOCOL_BUDGET = 18.0


def family_weights(counts: dict[str, int],
                   budgets: dict[str, float] | None = None) -> dict[str, float]:
    """Per-case weight for each family, from its budget and its size.

    A family present in the cases but absent from the budget table is a
    generator that grew a family this file was never told about.  It gets the
    mean budget rather than zero -- silently grading something at zero is how a
    suite ends up with cases nobody notices are unscored -- and `check_catalog`
    reports it as drift.
    """
    table = FAMILY_BUDGETS if budgets is None else budgets
    if not counts or not table:
        return {}
    fallback = sum(table.values()) / len(table)
    out: dict[str, float] = {}
    for family, count in counts.items():
        if count <= 0:
            continue
        out[family] = table.get(family, fallback) / count
    return out


def unknown_families(counts: dict[str, int],
                     budgets: dict[str, float] | None = None) -> list[str]:
    table = FAMILY_BUDGETS if budgets is None else budgets
    return sorted(set(counts) - set(table))


def missing_families(counts: dict[str, int],
                     budgets: dict[str, float] | None = None) -> list[str]:
    table = FAMILY_BUDGETS if budgets is None else budgets
    return sorted(set(table) - set(counts))


