# -- provenance of the artefact ----------------------------------------------
# The four anti-cheat questions that can only be answered by something that
# watched the build run or that holds the binary it produced.  A reader of the
# source cannot answer any of them: the shim ledger exists only during the build,
# and the other three are properties of a file that does not exist until it ends.
#
# The rest of the anti-cheat surface -- whether a *.go survived, whether the tree
# vendors a C library, whether an environment variable picks between two parsers
# -- is a reading of the submission, and stage 1 does the reading.  Restating
# those here would grade the same evidence twice, and worse, would do it with a
# regular expression where stage 1 has an agent that can tell a comment
# mentioning Go from a call into it.
#
# The fourth field is not a grading input: nothing in the grader reads it for a
# behavioural check
# (swerefactor/behavioural.py clears `required` on every check it collects, and
