#!/usr/bin/env python3
"""Generate a downstream module that type-checks every published symbol.

The obvious way to grade a published API is to dump the submission's declarations
and compare them against the contract's list.  That was the retired approach here,
and it is a comparison of *text the submission wrote about itself*: it catches a
missing symbol and a renamed parameter type, and it is self-consistent by
construction, because both sides of it are derived from the same source file.

What it cannot do is establish that the declared types compose.  `sql.NewGroup(Kind,
[]*Node) *Node` and `value KindWhere` can both be spelled exactly right while
`KindWhere` is not a `Kind`, or while `Kind` is a struct that cannot be a constant,
or while `*Node` in one package is not the `*Node` the other returns.  Nothing
detects that except a compiler, and 40 of the contract's 155 symbols -- most of
`sql`'s 22 Kind constants, nine token types, `engine.SplitStatements`,
`formatter.Options.ToMap`, `keywords.All`, `lexer.New`, `utils.Offset` -- are named
by no probe tier, so before this file nothing compiled against them at all.

So this emits a module that names every contract symbol in a position where the
type has to be right:

  * a func or method becomes `var _ <declared type> = <expr>`, which is the
    strictest available assertion -- Go checks assignability against the full
    signature, so a wrong parameter order, a missing error result or a differently
    named-but-differently-shaped type all fail to compile;
  * a method becomes a method expression (`(*sql.Node).SetParent`), which is how a
    method's signature is written down as a value;
  * a value becomes `var _ = <pkg>.<Name>`, plus a typed assertion for the ones the
    contract gives a type to (the Kind constants and the token types), because an
    untyped `var _ =` would accept anything;
  * a type becomes a declared variable of that type, which is what fails if the
    type is not exported, or is a type alias to something unusable.

It is a separate module with its own go.mod and a `replace` at grading time, for
the same reason the probe is: it must be a *downstream* consumer.  A submission
that put its public API behind `internal/` compiles its own tests fine and fails
here, which is the second thing this file establishes.

Generated at freeze time from the contract rather than written by hand, so a
contract change cannot leave a stale conformance file that still compiles.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from skeleton import Signature, split_types

HERE = Path(__file__).resolve().parent

# Which import a bare package qualifier in a signature needs.  `io` is the only
# non-module qualifier the contract uses; an unknown one is an error rather than a
# guess, because guessing would invent an import the contract never asked for.
STDLIB_QUALIFIERS = {"io": "io"}

# The contract gives these a type without spelling it in the symbol line: `value
# KindWhere` says nothing about Kind, and `value Keyword` nothing about TokenType.
# Written down here so the assertion is typed -- an untyped `var _ = pkg.KindWhere`
# would pass on a submission that made them strings.
VALUE_TYPES = {
    "sql": ("Kind", lambda name: name.startswith("Kind")),
    "tokens": ("TokenType", lambda name: name != "Version"),
}

HEADER = '''// Code generated by tests/conform.py at image build time. DO NOT EDIT.
//
// A downstream consumer that names every published symbol in a position where the
// compiler has to agree with the contract about its type.  It is never run: what
// is graded is whether it builds against the submission.
package conform
'''

BUILTINS = {"string", "int", "bool", "error", "any", "byte", "rune", "float64",
            "int64", "uint", "uint8", "int32"}


def short_name(pkg_dir: str, package_name: str) -> str:
    """The identifier a consumer writes to reach this package."""
    return package_name if pkg_dir == "." else pkg_dir.rsplit("/", 1)[-1]


def qualify(gotype: str, short: str) -> tuple[str, set[str]]:
    """Rewrite a contract type as a downstream consumer must spell it.

    The contract writes types as they appear *inside* the declaring package, so
    `sql`'s methods take `*Node` and `engine`'s take `*sql.Node` for the same type.
    From outside, both are `sql.Node`.  Returns the rewritten type and the set of
    package qualifiers it mentions, which is how the import block is computed --
    a generated file with a guessed import would fail to compile for a reason that
    has nothing to do with the submission.
    """
    out: list[str] = []
    quals: set[str] = set()
    index = 0
    while index < len(gotype):
        char = gotype[index]
        if char.isalpha() or char == "_":
            start = index
            while index < len(gotype) and (gotype[index].isalnum()
                                           or gotype[index] == "_"):
                index += 1
            word = gotype[start:index]
            if index < len(gotype) and gotype[index] == ".":
                # Already qualified: consume the selector too, or the exported
                # name after the dot gets qualified a second time and `sql.Node`
                # becomes `sql.sqlparse.Node`.
                index += 1
                sel_start = index
                while index < len(gotype) and (gotype[index].isalnum()
                                               or gotype[index] == "_"):
                    index += 1
                quals.add(word)
                out.append(f"{word}.{gotype[sel_start:index]}")
                continue
            if word in BUILTINS:
                out.append(word)
                continue
            if word[:1].isupper():
                # A bare exported name is declared in the package being emitted.
                quals.add(short)
                out.append(f"{short}.{word}")
            else:
                out.append(word)
            continue
        out.append(char)
        index += 1
    return "".join(out), quals


def func_type(sig: Signature, short: str, *, receiver: str = "") -> tuple[str, set[str]]:
    """The declared type of a func or method, as a Go type literal.

    A method's type is its method-expression type: the receiver becomes the first
    parameter, which is exactly what `(*sql.Node).SetParent` evaluates to.  Writing
    it that way means one assertion covers the receiver as well as the signature,
    and covers it in the pointer-ness the contract declared -- a method moved from
    `*Node` to `Node` changes this type and fails to compile.
    """
    quals: set[str] = set()
    params: list[str] = []
    if receiver:
        text, found = qualify(receiver, short)
        params.append(text)
        quals |= found
    for param in sig.params:
        text, found = qualify(param, short)
        params.append(text)
        quals |= found
    results: list[str] = []
    for result in sig.results:
        text, found = qualify(result, short)
        results.append(text)
        quals |= found
    rendered = "func(" + ", ".join(params) + ")"
    if len(results) == 1:
        rendered += " " + results[0]
    elif results:
        rendered += " (" + ", ".join(results) + ")"
    return rendered, quals


def emit(contract: dict) -> tuple[str, int]:
    """The conformance file's text, and how many symbols it asserts.

    One `var _` per symbol, grouped by package in contract order.  `var _` rather
    than a named variable because nothing reads these: the declaration is the whole
    assertion, and an unused named variable would not compile.
    """
    go = contract["go_contract"]
    module = go["module_path"]
    lines: list[str] = []
    imports: set[str] = set()
    asserted = 0

    for pkg_dir, spec in sorted(go["packages"].items()):
        symbols = spec["symbols"]
        if not symbols:
            continue  # cmd/sqlformat: a main package has nothing to import
        short = short_name(pkg_dir, spec["package_name"])
        import_path = module if pkg_dir == "." else f"{module}/{pkg_dir}"
        imports.add(import_path)
        lines.append(f"// -- {import_path} --")
        value_type, value_wants = VALUE_TYPES.get(short, ("", None))

        for raw in symbols:
            sig = Signature(raw)
            if sig.kind == "type":
                # A variable of the type: fails if the type is unexported, absent,
                # or an alias to something that cannot be a variable.  Interfaces
                # and structs both work as a declared type with no initializer.
                lines.append(f"var _ {short}.{sig.name}")
                asserted += 1
            elif sig.kind == "func":
                gotype, quals = func_type(sig, short)
                imports |= {q for q in quals if q in STDLIB_QUALIFIERS}
                lines.append(f"var _ {gotype} = {short}.{sig.name}")
                asserted += 1
            elif sig.kind == "method":
                recv = sig.recv
                base = recv.lstrip("*")
                # The receiver is written from outside: `*Node` inside sql is
                # `*sql.Node` here, and the method expression needs the
                # parenthesized form for a pointer receiver.
                outer = ("*" if recv.startswith("*") else "") + f"{short}.{base}"
                gotype, quals = func_type(sig, short, receiver=outer)
                imports |= {q for q in quals if q in STDLIB_QUALIFIERS}
                expr = f"({outer}).{sig.name}"
                lines.append(f"var _ {gotype} = {expr}")
                asserted += 1
            elif sig.kind == "value":
                if value_type and value_wants and value_wants(sig.name):
                    lines.append(
                        f"var _ {short}.{value_type} = {short}.{sig.name}")
                else:
                    # No declared type in the contract, so the assertion is only
                    # that the name exists and is exported.  `Version` is the one
                    # of these; its value is graded by the version case, not here.
                    lines.append(f"var _ = {short}.{sig.name}")
                asserted += 1
            else:  # pragma: no cover - Signature raises on anything else
                raise SystemExit(f"conform: unhandled symbol kind: {raw}")
        lines.append("")

    resolved = sorted(STDLIB_QUALIFIERS[q] for q in imports
                      if q in STDLIB_QUALIFIERS)
    resolved += sorted(p for p in imports if p not in STDLIB_QUALIFIERS)
    block = "\n".join(f'\t"{path}"' for path in resolved)
    text = HEADER + f"\nimport (\n{block}\n)\n\n" + "\n".join(lines)
    return text, asserted


def write(contract: dict, out: Path) -> tuple[int, int]:
    """Write the conformance module.  Returns (symbols asserted, packages).

    The `replace` is a fixed relative path, spelled the same way the probe module
    spells it, and for the same reason: build.py stages this module as a sibling of
    the staged submission, so `../submission` is what the path is by construction
    rather than a guess about the grading layout.  Writing it here instead of
    patching go.mod at grading time also means the module in the image is the module
    that gets compiled -- freeze.py builds it against the skeleton through the same
    two files, so a directive that resolves to nothing fails the image build.
    """
    go = contract["go_contract"]
    out.mkdir(parents=True, exist_ok=True)
    text, asserted = emit(contract)
    (out / "conform.go").write_text(text)
    (out / "go.mod").write_text(
        "// The conformance consumer: generated from the contract at image build\n"
        "// time, compiled against the submission at grading time.  Nothing here is\n"
        "// ever run -- every assertion in conform.go is resolved by the type\n"
        "// checker, so the build succeeding is the whole result.\n"
        f"module conform\n\ngo 1.25\n\n"
        f"require {go['module_path']} v0.0.0\n\n"
        f"replace {go['module_path']} => ../submission\n"
    )
    packages = sum(1 for spec in go["packages"].values() if spec["symbols"])
    return asserted, packages


def main() -> int:
    contract = json.loads((HERE / "source-contract.json").read_text())
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "consumer"
    asserted, packages = write(contract, out)
    print(f"wrote {out}: {asserted} assertions over {packages} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
