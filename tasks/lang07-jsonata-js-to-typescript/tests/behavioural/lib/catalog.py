#!/usr/bin/env python3
"""What lang07 measures, in one inventory.

The corpus itself is generated by `gen.py`, because only the JavaScript reference
can say what jsonata does with a given expression -- including the expressions
jsonata rejects, where the answer is an error code and a position rather than a
value.  What this module owns is everything the corpus does not: how much each
family is worth, which module owns it, the type-surface cases, the structural cases,
and the inventory of error codes the corpus is expected to reach.

The weighting is the part worth reading.  The corpus is deliberately lopsided --
`compose` has 2,240 cases because composing atoms is cheap and `regex` has 65
because there are only so many interesting regular expressions -- so grading per
case would make the composer worth thirty times the regex engine, which is not what
a reader of this task would say those two things are worth to it.  So each family
gets a budget, and its cases divide that budget equally.  A family's importance is
then a declared number in this file rather than an accident of how many cases it was
cheap to generate.

One structural note that separates this task from its siblings.  The old runtime and
the new runtime are the same runtime: a JavaScript library ported to TypeScript
still runs on `node`, so there is no toolchain to remove from the grading image and
no PATH to strip.  Nothing in this file tries to compensate for that -- cheat
detection is stage 1's reading gates.  What this file does is make the *behavioural*
measurement hard to pass without porting: a corpus generated from a seed the
submission never saw, and a type surface measured by compiling fixed consumer
programs against whatever declarations the submission's build emitted.
"""

