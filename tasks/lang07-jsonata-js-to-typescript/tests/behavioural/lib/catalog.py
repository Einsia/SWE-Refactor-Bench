# -- structural cases --------------------------------------------------------
# What the `structure` module grades.  Three rules govern membership, and they are
# restrictive on purpose -- the previous version of this table had ten rows and
# most of them were assertions about files:
#
#   1. Nothing else may already measure it. A rule the corpus enforces by
#      answering cases does not need a row here, and a row here would charge the
#      submission twice for one defect.
#   2. A submission must be able to fail it while passing everything else.
#      A row that no plausible submission fails independently is not a
#      measurement, it is decoration.
#   3. The rule must be stated in `instruction.md` and in
#      `environment/source-contract.json`. A submission cannot be graded on a
#      requirement it was never given.
#
