PANIC_CAUSES: tuple[str, ...] = ("type", "error")

# -- modules -----------------------------------------------------------------
# Which families each module owns.  A module's weight in `suite.toml` is the sum
# of its families' budgets, so a case's share of the stage is
# (module weight / total) x (1 / cases in that case's family) x (family budget /
# module weight) -- which reduces to: every case is worth its family's budget
# divided by its family's size, and the module boundary only decides which
# subprocess reports it and which failures are diagnosed together.
#
# The split is by what a reader would want reported separately, not by size. If
# `datetime` fails and nothing else does, that is a picture-string bug and the
# module map should say so in one line.
MODULE_FAMILIES: dict[str, tuple[str, ...]] = {
    # `build` owns no family and carries weight 0, and it is the one module here
    # for which that is right.  It is not scored because it is not a measurement:
    # it runs the repository's build and writes the ledger every module below
    # reads, so the build happens once instead of fifteen times.  Its cost is
    # already paid in full through those modules -- a tree that does not build
    # fails every family, and the stage totals 0.
    "build":        (),
    # Behaviour of the built artifact as an artifact.
    "structure":    ("_release",),
    # The language, family by family.
    "navigation":   ("paths",),
    "operators":    ("operators", "numbers"),
    "strings":      ("strings", "encoding", "regex"),
    "datetime":     ("datetime",),
    "collections":  ("collections",),
    "lambdas":      ("behavioural", "register"),
    "transform":    ("transform",),
    "errors":       ("errors", "syntax"),
    # The embedding API: the two calling conventions, the options, the two ways
    # to install a binding, evaluating one compiled expression twice, and the
    # transport rules that carry all of it.
    "api":          ("options", "bindings", "assigns", "callback", "repeat",
                     "_protocol"),
    # Composed expressions, kept apart from the families they are composed from
    # so that "the atoms work but combining them does not" is one line in the
    # report rather than a diffuse loss.
    "compose":      ("compose",),
    # jsonata's own published suite.
    "suite":        ("_fixture",),
    # The held-out corpus.
    "fresh":        ("fresh-composed", "fresh-mutated"),
    # The type surface.
    "types":        ("_types",),
}

# The modules that publish something the others read rather than measuring
# anything.  `build` is the only one: it writes the build ledger, which is why it
# is allowed weight 0 while any other weight-0 module is rejected by
# `check_suite_weights` as a check nothing can be paid for.
#
# A set rather than a bare string comparison because the loops below read it as
# one, and an emptied set would still let every loop run, over nothing, and read
# as a live rule with no members.
# reader would have to prove the emptiness was intended rather than a bug.
MODULES_PUBLISHING_A_LEDGER: frozenset[str] = frozenset({"build"})

# Families whose cases do not come from the corpus, and so must be excluded when
# comparing the families `gen.py` emits against the families budgeted here.
# `_release` is graded by running the built artifact; `_types` by compiling
# against its declarations.  Both still carry budgets -- see `gen.py`'s
# self-check, which asserts exactly that, because a family excluded from the
# comparison and also absent from the budget would take its module's points with
# it and no check would notice.
NON_CORPUS_FAMILIES: frozenset[str] = frozenset({"_release", "_types"})

# Case floors.  These are the numbers the weighting above assumes; a corpus that
# shrank below one of them would still self-check clean while grading something
# much thinner than this file describes.
MIN_STRUCT_CASES = 6
MIN_CORPUS_CASES = 10000
MIN_FRESH_CASES = 1200
MIN_FIXTURE_CASES = 1500
MIN_PROTOCOL_CASES = 90
MIN_TYPE_CASES = 24
MIN_CODES_REACHED = 90

# How far a percentage written into a module's `about` may sit from the one this
# file computes.  The prose says "about 8%"; it does not have to say 8.104%.
PROSE_PCT_TOLERANCE = 0.05


# -- derived -----------------------------------------------------------------

def all_budgets() -> dict[str, float]:
    """Every family with a budget, corpus and non-corpus alike."""
    out: dict[str, float] = dict(FAMILY_BUDGETS)
    out.update(FRESH_BUDGETS)
    out["_protocol"] = PROTOCOL_BUDGET
    out["_release"] = RELEASE_BUDGET
    out["_types"] = TYPES_BUDGET
    return out


def budget_total() -> float:
    return sum(all_budgets().values())


def module_weights() -> dict[str, float]:
    """The weights `suite.toml` must carry, verbatim."""
    budgets = all_budgets()
    return {
        module: round(sum(budgets[family] for family in families), 3)
        for module, families in MODULE_FAMILIES.items()
    }


def module_of(family: str) -> str:
    for module, families in MODULE_FAMILIES.items():
        if family in families:
            return module
    raise KeyError(f"no module owns family {family!r}")


def family_weights(counts: dict[str, int]) -> dict[str, float]:
    """Per-case weight within each family: its budget spread over its cases.

    `counts` is the real corpus count, so this is the only place the two halves
    meet -- the budgets in this file and the cases `gen.py` emitted.

    A family with a budget and no cases is a hole and raises. A family with cases
    and no budget cannot be silently dropped either: it gets the mean budget so
    its cases still score, and it is reported as drift so somebody fixes the
    table rather than discovering later that a family was graded at a number
    nobody chose.
    """
    budgets = all_budgets()
    drift: list[str] = []
    mean = budget_total() / max(len(budgets), 1)
    weights: dict[str, float] = {}
    for family, n in sorted(counts.items()):
        if n <= 0:
            raise ValueError(f"family {family!r} has {n} cases")
        if family in budgets:
            weights[family] = budgets[family] / n
        else:
            weights[family] = mean / n
            drift.append(family)
    for family, budget in sorted(budgets.items()):
        if family in NON_CORPUS_FAMILIES:
            continue
        if family not in counts:
            raise ValueError(
                f"family {family!r} carries a budget of {budget} and has no "
                f"cases, so those points would spread over the other families "
                f"silently"
            )
    if drift:
        print(f"catalog: unbudgeted families graded at the mean: {drift}",
              file=sys.stderr)
    return weights


def release_weights() -> dict[str, float]:
    """Per-case weights for the structural cases, summing to RELEASE_BUDGET.

    Keyed by case id -- `struct/<check>` -- because that is what the driver records
    and what `structure.py` looks itself up under. Keying by the bare check name
    would make every lookup in that file a silent miss scoring the 1.0 default.
    """
    return {f"struct/{check}": float(weight) for check, weight, _ in STRUCT_CASES}


def type_weights() -> dict[str, float]:
    """Per-case weights for the type-surface cases, summing to TYPES_BUDGET."""
    return {cid: float(weight) for cid, _, weight, _, _ in TYPE_CASES}


def type_accept(case_id: str) -> tuple[int, ...]:
    """The diagnostic codes that mean a negative was rejected for its reason."""
    for cid, kind, _, accept, _ in TYPE_CASES:
        if cid == case_id:
            if kind != "negative":
                raise KeyError(f"{case_id} is a {kind}, and has no accept-set")
            return accept
    raise KeyError(f"no type case {case_id!r}")


def type_cases_of(kind: str) -> tuple[str, ...]:
    return tuple(cid for cid, k, _, _, _ in TYPE_CASES if k == kind)


def _load_toml(path: Path) -> dict:
    """Read one TOML file on 3.10 as well as 3.11+.

    The verifier image is 3.11+, but this module is also imported by the host-side
    authoring checker, and an author's machine is whatever it is.  `tomli` is the
    documented fallback; if neither reader exists the caller gets an exception
    rather than a silent skip, because "this check could not run" must never be
    reported as "these weights are correct".
    """
    try:
        import tomllib as reader  # type: ignore[import-not-found]
    except ModuleNotFoundError:
        try:
            import tomli as reader  # type: ignore[no-redef]
        except ModuleNotFoundError:
            raise RuntimeError(
                "no TOML reader available: run on Python 3.11+ or "
                "`pip install tomli`")
    with open(path, "rb") as fh:
        return reader.load(fh)


def check_suite_weights(suite_path: Path) -> list[str]:
    """`suite.toml`'s declared weights against the budgets they must sum to.

    The check exists because the two files are edited days apart.  A family budget
    raised in this file and not reflected in `suite.toml` does not break anything
    visibly: the suite still runs, every case still gets a verdict, and the stage
    still produces a score.  It is just a different score from the one the comments
    above claim to describe, and nothing else would ever notice.
    """
    problems: list[str] = []
    if not suite_path.exists():
        return [f"{suite_path} does not exist, so its weights cannot be checked"]
    try:
        raw = _load_toml(suite_path)
    except RuntimeError as exc:
        return [f"{suite_path}: {exc}"]
    except Exception as exc:  # a malformed suite is a problem, not a crash
        return [f"{suite_path} is unreadable: {exc}"]
    entries = raw.get("module") or []
    declared: dict[str, tuple[float, bool]] = {}
    for entry in entries:
        mid = str(entry.get("id", ""))
        if not mid:
            problems.append(f"{suite_path.name}: a [[module]] has no id")
            continue
        declared[mid] = (float(entry.get("weight", 1.0)),
                         bool(entry.get("required", False)))
    want = module_weights()
    extra = sorted(set(declared) - set(want))
    absent = sorted(set(want) - set(declared))
    if extra:
        problems.append(
            f"{suite_path.name} declares module(s) with no entry in "
            f"MODULE_FAMILIES: {', '.join(extra)}; a module that owns no families "
            f"is scoring nothing or scoring something this file does not know "
            f"about")
    if absent:
        problems.append(
            f"MODULE_FAMILIES names module(s) absent from {suite_path.name}: "
            f"{', '.join(absent)}; their families would never run")
    for mid in sorted(set(declared) & set(want)):
        got = declared[mid][0]
        if abs(got - want[mid]) > 1e-6:
            owned = ", ".join(MODULE_FAMILIES[mid]) or "nothing"
            problems.append(
                f"module {mid!r} declares weight {got:g} but owns {owned}, which "
                f"sums to {want[mid]:g}")
    # Weight 0 is allowed for exactly one reason, and the check is what keeps it to
    # one.  A weight-0 module reports something it is paid nothing for, which is
    # only defensible when what it publishes is read by the modules that ARE paid --
    # `build` and nothing else.  Then its cost is charged through them: a failed
    # build fails every family below it.
    for mid, (weight, required) in sorted(declared.items()):
        if weight == 0.0 and mid not in MODULES_PUBLISHING_A_LEDGER:
            problems.append(
                f"module {mid!r} has weight 0 and publishes no ledger any scored "
                f"module reads, so nothing it reports can affect the score; give "
                f"it a weight or delete it")
        if weight > 0.0 and mid in MODULES_PUBLISHING_A_LEDGER:
            problems.append(
                f"module {mid!r} publishes the ledger and also carries weight "
                f"{weight:g}, so a build failure is charged twice -- once here "
                f"and once through every family that could not run")
        if required:
            problems.append(
                f"{suite_path.name} marks module {mid!r} required; `required` is "
                f"not a module key and the runner refuses a suite that declares "
                f"one, so a reader would take it for a veto the stage does not draw")
    meta = raw.get("metadata") or {}
    if "weight_total" in meta:
        want_total = round(sum(want.values()), 3)
        if abs(float(meta["weight_total"]) - want_total) > 1e-6:
            problems.append(
                f"{suite_path.name} [metadata] weight_total is "
                f"{meta['weight_total']}, but the budgets sum to {want_total:g}")
    problems.extend(check_suite_prose(entries, want))
    return problems


# 13,940 -- written in `[metadata] corpus_cases` and again in `[metadata] about`.
_CASES_PROSE_RE = re.compile(r"([0-9][0-9,]*)\s+frozen cases")


def check_suite_corpus(suite_path: Path, counts: dict[str, int]) -> list[str]:
    """`suite.toml`'s case count against the corpus actually on disk.

    Two numbers, both hand-written: `[metadata] corpus_cases`, and the same figure
    spelled with a comma in the metadata prose.  Neither affects grading -- the
    runner counts cases itself -- which is exactly why they rot unnoticed.  This
    total moved by 18 the last time a generator gained three expressions, and
    fourteen files had to be edited to follow it; two of them were found by
    grepping for the old digits, not by anything failing.

    Only reachable with both `--corpus` and `--suite`, and silent when the suite
    states no count: an absent number cannot be wrong.  A *stated* one is checked
    against the sum over corpus-bearing families, which is what the stems hold --
    `_release` and `_types` are generated at grade time and counted nowhere on disk.
    """
    problems: list[str] = []
    if not counts or not suite_path.exists():
        return problems
    try:
        raw = _load_toml(suite_path)
    except Exception:
        return problems  # already reported by check_suite_weights
    meta = raw.get("metadata") or {}
    actual = sum(n for family, n in counts.items()
                 if family not in NON_CORPUS_FAMILIES)
    if "corpus_cases" in meta:
        if int(meta["corpus_cases"]) != actual:
            problems.append(
                f"{suite_path.name} [metadata] corpus_cases is "
                f"{meta['corpus_cases']}, but the corpus holds {actual}")
    found = _CASES_PROSE_RE.search(str(meta.get("about") or ""))
    if found:
        claimed = int(found.group(1).replace(",", ""))
        if claimed != actual:
            problems.append(
                f"{suite_path.name} [metadata] about says {found.group(1)} frozen "
                f"cases, but the corpus holds {actual}")
    return problems


_PCT_RE = re.compile(r"([0-9]+(?:\.[0-9]+)?)%")
# `paths` 190, `_fixture` 130 -- the per-family arithmetic the shares are built
# from, spelled out in the same prose.  Matched only for backticked names that are
# real families, so ordinary prose containing a number cannot be mistaken for a
# claim.
#
# The leading `_?` is not cosmetic.  Without it the four generated families --
# `_release`, `_protocol`, `_fixture`, `_types` -- did not match, so their numbers
# in the prose were never compared against anything.  Those four are the *only*
# family number in `structure`, `api`'s tail, `suite` and `types`, which meant
# three modules' arithmetic went unchecked while the check reported success: a
# `_fixture` deliberately written as 125 against a budget of 130 passed.  Anything
# that reads a name out of prose has to use the same alphabet the names are drawn
# from, and these names start with an underscore.
_FAMILY_NUM_RE = re.compile(r"`(_?[a-z][a-z-]*)`\s+([0-9]+(?:\.[0-9]+)?)\b")


def check_suite_prose(entries: list, want: dict[str, float]) -> list[str]:
    """The percentages and per-family numbers written into each module's `about`.

    `check_suite_weights` proves the machine-readable weights are the budget sums.
    This proves the *prose* beside them says the same thing, which is the half a
    reader actually reads and the half nothing else in this file touches.  Every
    scored module's `about` opens with its share of the stage; fifteen numbers,
    none derived at read time, all stale the moment a budget moves.

    Tolerance is half of the last published digit.  The strings carry one decimal,
    so 0.05 accepts a correctly rounded number and rejects one that came from a
    different weight.
    """
    problems: list[str] = []
    total = sum(want.values())
    if not total:
        return problems
    budgets = all_budgets()
    for entry in entries:
        mid = str(entry.get("id", ""))
        about = str(entry.get("about", "") or "")
        if not mid or mid not in want:
            continue
        share = 100.0 * want[mid] / total
        found = _PCT_RE.search(about)
        if want[mid] == 0.0:
            # The two gates carry no share, so a percentage in their prose would
            # be claiming one.  Checked rather than skipped: "0.0%" is the wrong
            # way to describe a veto.
            if found:
                problems.append(
                    f"module {mid!r} has weight 0 but its `about` claims "
                    f"{found.group(0)} of the stage; a gate has no share")
            continue
        if not found:
            problems.append(
                f"module {mid!r} carries {share:.1f}% of the stage and its "
                f"`about` states no percentage; every scored module publishes its "
                f"share, and an absent one cannot go stale but also cannot be "
                f"checked")
            continue
        claimed = float(found.group(1))
        if abs(claimed - share) > PROSE_PCT_TOLERANCE:
            problems.append(
                f"module {mid!r} weighs {want[mid]:g} of {total:g}, which is "
                f"{share:.1f}% of the stage, but its `about` says "
                f"{found.group(0)}")
        for name, number in _FAMILY_NUM_RE.findall(about):
            if name not in budgets:
                continue
            if abs(float(number) - budgets[name]) > 1e-6:
                problems.append(
                    f"module {mid!r} prose gives family {name!r} as {number}, but "
                    f"its budget is {budgets[name]:g}")
    return problems


def check_module_map() -> list[str]:
    """Every family owned exactly once, and every owned name real."""
    problems: list[str] = []
    budgets = all_budgets()
    owned: dict[str, list[str]] = {}
    for module, families in MODULE_FAMILIES.items():
        for family in families:
            owned.setdefault(family, []).append(module)
            if family not in budgets:
                problems.append(
                    f"module {module!r} claims family {family!r}, which has no "
                    f"budget; a module cannot own a family that is not scored")
    for family, modules in sorted(owned.items()):
        if len(modules) > 1:
            problems.append(
                f"family {family!r} is claimed by {len(modules)} modules "
                f"({', '.join(sorted(modules))}); its cases would be scored twice")
    for family in sorted(set(budgets) - set(owned)):
        problems.append(
            f"family {family!r} has a budget of {budgets[family]:g} but no owning "
            f"module, so none of its cases would run")
    return problems


def family_counts_in(path: Path) -> dict[str, int]:
    """Count cases per family in a corpus file, without importing `gen`."""
    counts: dict[str, int] = {}
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            family = json.loads(line)["family"]
            counts[family] = counts.get(family, 0) + 1
    return counts


def summary(counts: dict[str, int] | None = None) -> str:
    """The inventory as a table, for a human deciding whether it is right."""
    budgets = all_budgets()
    total = budget_total()
    weights = module_weights()
    lines = [f"{'module':<13} {'weight':>9} {'share':>7}  families"]
    lines.append("-" * 78)
    for module in MODULE_FAMILIES:
        share = 100.0 * weights[module] / total if total else 0.0
        owned = ", ".join(MODULE_FAMILIES[module]) or "(ledger)"
        flag = ("  [publishes the ledger, unscored]"
                if module in MODULES_PUBLISHING_A_LEDGER else "")
        lines.append(f"{module:<13} {weights[module]:>9.3f} {share:>6.2f}%  "
                     f"{owned}{flag}")
    lines.append("-" * 78)
    lines.append(f"{'total':<13} {total:>9.3f} {100.0:>6.2f}%")
    lines.append("")
    lines.append(f"{'family':<18} {'budget':>8} {'share':>7} {'cases':>7} "
                 f"{'per case':>10}")
    lines.append("-" * 78)
    for family, budget in sorted(budgets.items(), key=lambda kv: -kv[1]):
        share = 100.0 * budget / total if total else 0.0
        if counts and family in counts:
            n = counts[family]
            lines.append(f"{family:<18} {budget:>8.1f} {share:>6.2f}% {n:>7} "
                         f"{budget / n:>10.4f}")
        else:
            lines.append(f"{family:<18} {budget:>8.1f} {share:>6.2f}% "
                         f"{'-':>7} {'-':>10}")
    lines.append("")
    lines.append(f"type cases: {len(TYPE_CASES)} "
                 f"({len(type_cases_of('positive'))} positive, "
                 f"{len(type_cases_of('negative'))} negative), "
                 f"budget {TYPES_BUDGET:g}")
    lines.append(f"structural cases: {len(STRUCT_CASES)}, "
                 f"budget {RELEASE_BUDGET:g} "
                 f"({STRUCT_CASES_ORIGINAL} drafted, {STRUCT_CASES_DROPPED} "
                 f"dropped, {STRUCT_CASES_READDED} restored, "
                 f"{STRUCT_CASES_ADDED} added later)")
    lines.append(f"error codes: {len(CODES_REACHED)} reached of "
                 f"{CODES_DECLARED_TOTAL}; {len(CODES_UNREACHED)} unreached, "
                 f"each with a measured reason")
    return "\n".join(lines)


def check_catalog(counts: dict[str, int] | None = None,
                  suite_path: Path | None = None) -> list[str]:
    """Everything this file asserts about itself, as a list of problems.

    Returned rather than raised so a caller can print all of them at once; the
    build asserts the list is empty.
    """
    problems: list[str] = []
    problems.extend(check_module_map())

    budgets = all_budgets()
    total = budget_total()
    for family, budget in sorted(budgets.items()):
        if budget <= 0:
            problems.append(f"family {family!r} has budget {budget:g}")

    # Proportion caps.  Each of these is a claim about what the stage is *about*,
    # and each was a real risk while the budgets were being written: it is easy to
    # give the envelope and the packaging a few more points each and end up with a
    # stage where a tenth of the score has nothing to do with jsonata.
    if total:
        proto_pct = 100.0 * PROTOCOL_BUDGET / total
        release_pct = 100.0 * RELEASE_BUDGET / total
        types_pct = 100.0 * TYPES_BUDGET / total
        fresh_pct = 100.0 * sum(FRESH_BUDGETS.values()) / total
        if proto_pct > 3.0:
            problems.append(
                f"the protocol family is {proto_pct:.2f}% of the stage; it grades "
                f"an envelope and must stay under 3%")
        if release_pct > 3.0:
            problems.append(
                f"the structural cases are {release_pct:.2f}% of the stage; they "
                f"grade packaging and must stay under 3%")
        if proto_pct + release_pct > 5.0:
            problems.append(
                f"protocol plus structure is {proto_pct + release_pct:.2f}% of the "
                f"stage; together they must stay under 5%, or a submission could "
                f"lose a twentieth of the stage without a single wrong answer")
        if types_pct > 12.0:
            problems.append(
                f"the type surface is {types_pct:.2f}% of the stage; it is half of "
                f"what the port means but it is 24 cases, and above 12% a single "
                f"declaration mistake would outweigh a whole language family")
        if types_pct < 4.0:
            problems.append(
                f"the type surface is {types_pct:.2f}% of the stage; below 4% a "
                f"submission could ship `declare const jsonata: any` and lose "
                f"almost nothing, which is the one outcome this task must not "
                f"permit")
        if fresh_pct < 10.0:
            problems.append(
                f"the held-out corpus is {fresh_pct:.2f}% of the stage; below 10% "
                f"a submission that carried pre-computed answers instead of "
                f"porting an engine would still score well")

    # The type table.
    if len(TYPE_CASES) < MIN_TYPE_CASES:
        problems.append(
            f"{len(TYPE_CASES)} type cases, floor is {MIN_TYPE_CASES}")
    seen_types: set[str] = set()
    for cid, kind, weight, accept, note in TYPE_CASES:
        if cid in seen_types:
            problems.append(f"type case {cid!r} is listed twice")
        seen_types.add(cid)
        if kind not in ("positive", "negative"):
            problems.append(f"type case {cid!r} has kind {kind!r}")
        if weight <= 0:
            problems.append(f"type case {cid!r} has weight {weight:g}")
        if len(note) < 30:
            problems.append(
                f"type case {cid!r} has a {len(note)}-character note; a row "
                f"nobody can review is a row nobody will maintain")
        if kind == "negative":
            if not accept:
                problems.append(
                    f"negative {cid!r} declares no accept-set, so any rejection "
                    f"at all would score -- including a rejection for a defect "
                    f"another case already grades")
            for code in accept:
                if not 1000 <= code <= 9999:
                    problems.append(f"negative {cid!r}: TS{code} is not a code")
        elif accept:
            problems.append(
                f"positive {cid!r} carries an accept-set, which means nothing: a "
                f"positive must produce no diagnostics at all")
    pos, neg = len(type_cases_of("positive")), len(type_cases_of("negative"))
    if pos < 8 or neg < 8:
        problems.append(
            f"the type surface has {pos} positives and {neg} negatives; both "
            f"halves must be substantial -- positives alone accept `any`, and "
            f"negatives alone accept a declaration too strict to use")
    # Filename order is the on-disk order, and `p`/`n` prefixes are how
    # `types-surface.py` knows which way to read an exit code.
    for cid, kind, *_ in TYPE_CASES:
        want_prefix = "p" if kind == "positive" else "n"
        if not cid.startswith(want_prefix):
            problems.append(
                f"type case {cid!r} is a {kind} but does not start with "
                f"{want_prefix!r}; the prefix is what says how to read tsc's "
                f"exit code")

    # The structural table.
    if len(STRUCT_CASES) < MIN_STRUCT_CASES:
        problems.append(
            f"{len(STRUCT_CASES)} structural cases, floor is {MIN_STRUCT_CASES}")
    if STRUCT_CASES_ORIGINAL - STRUCT_CASES_DROPPED + STRUCT_CASES_READDED + \
            STRUCT_CASES_ADDED != len(STRUCT_CASES):
        problems.append(
            f"the structural tally does not reconcile: "
            f"{STRUCT_CASES_ORIGINAL} - {STRUCT_CASES_DROPPED} + "
            f"{STRUCT_CASES_READDED} + {STRUCT_CASES_ADDED} != "
            f"{len(STRUCT_CASES)}")
    if len(STRUCT_DROPS) != STRUCT_CASES_DROPPED:
        problems.append(
            f"{len(STRUCT_DROPS)} rows in STRUCT_DROPS but "
            f"{STRUCT_CASES_DROPPED} claimed dropped; a drop without a recorded "
            f"reason reads as a weakening")
    seen_struct: set[str] = set()
    for check, weight, note in STRUCT_CASES:
        if check in seen_struct:
            problems.append(f"structural case {check!r} is listed twice")
        seen_struct.add(check)
        if weight <= 0:
            problems.append(f"structural case {check!r} has weight {weight:g}")
        if len(note) < 40:
            problems.append(
                f"structural case {check!r} has a {len(note)}-character note; "
                f"each row must say what a submission that fails it got wrong")
    for check, where in STRUCT_DROPS:
        if check in seen_struct:
            problems.append(
                f"{check!r} is both a structural case and recorded as dropped")
        if len(where) < 40:
            problems.append(
                f"drop {check!r} does not say where it went instead")

    # The error-code inventory.
    if len(CODES_REACHED) < MIN_CODES_REACHED:
        problems.append(
            f"{len(CODES_REACHED)} codes reached, floor is {MIN_CODES_REACHED}")
    if len(set(CODES_REACHED)) != len(CODES_REACHED):
        problems.append("CODES_REACHED has duplicates")
    overlap = sorted(set(CODES_REACHED) & set(CODES_UNREACHED))
    if overlap:
        problems.append(
            f"code(s) listed as both reached and unreached: {overlap}")
    if len(CODES_REACHED) + len(CODES_UNREACHED) != CODES_DECLARED_TOTAL:
        problems.append(
            f"{len(CODES_REACHED)} reached + {len(CODES_UNREACHED)} unreached != "
            f"{CODES_DECLARED_TOTAL} declared; a code in neither list is a code "
            f"nobody decided about")
    for code, reason in sorted(CODES_UNREACHED.items()):
        if len(reason) < 40:
            problems.append(
                f"unreached code {code} has no measured reason; the difference "
                f"between a gap in the corpus and a dead entry in jsonata's table "
                f"is only visible by attempting it")
    for code in CODES_UNDECLARED:
        if code not in CODES_REACHED:
            problems.append(
                f"{code} is recorded as undeclared-but-reached and is not in "
                f"CODES_REACHED")

    if counts is not None:
        try:
            family_weights(counts)
        except ValueError as exc:
            problems.append(str(exc))
        for stem, floor in (("_fixture", MIN_FIXTURE_CASES),
                            ("_protocol", MIN_PROTOCOL_CASES)):
            if stem in counts and counts[stem] < floor:
                problems.append(f"{stem}: {counts[stem]} cases, floor {floor}")

    if suite_path is not None:
        problems.extend(check_suite_weights(suite_path))
    return problems


def _self_check() -> None:
    """Run at import, so a broken inventory cannot be used by mistake."""
    problems = check_catalog()
    if problems:
        raise AssertionError(
            "catalog.py is inconsistent with itself:\n  " +
            "\n  ".join(problems))


_self_check()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="the lang07 grading inventory")
    ap.add_argument("--corpus", type=Path, default=None,
                    help="a *-cases.jsonl to count families in")
    ap.add_argument("--expected", type=Path, default=None,
                    help="the frozen expectations, to check code coverage in")
    ap.add_argument("--suite", type=Path, default=None,
                    help="suite.toml, whose weights must be the budget sums")
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if anything is inconsistent")
    ap.add_argument("--out", type=Path, default=None,
                    help="write the per-family weights here as JSON")
    args = ap.parse_args(argv)

    counts: dict[str, int] = {}
    if args.corpus:
        for path in ([args.corpus] if args.corpus.is_file()
                     else sorted(args.corpus.glob("*-cases.jsonl"))):
            for family, n in family_counts_in(path).items():
                counts[family] = counts.get(family, 0) + n

    problems = check_catalog(counts or None, args.suite)
    if args.suite and counts:
        problems.extend(check_suite_corpus(args.suite, counts))

    # Code coverage against the frozen expectations.  The inventory above was
    # measured once, by hand, against the reference; this is the check that it still
    # describes the corpus being graded.
    #
    # `--expected` takes either one file or the corpus directory.  A directory is the
    # useful form: coverage is a claim about the corpus as a whole, and `main` alone
    # reaches fewer codes than the four stems together, so checking one stem against
    # CODES_REACHED reports codes as missing that another stem reaches.
    if args.expected:
        # Imported here rather than at module scope because `freeze` imports this
        # module. By the time `main` runs, this one is fully initialised, so the
        # cycle resolves. Worth the awkwardness: `load_expected` is deliberately the
        # only reader of the format, and a second one here is exactly the drift it
        # exists to prevent -- the version this replaced looked for an `ordered` key
        # that no expectation file has ever had, found nothing, and reported nothing.
        import freeze  # noqa: PLC0415

        if args.expected.is_dir():
            files = sorted(args.expected.glob("*-expected.jsonl"))
        else:
            files = [args.expected]
        if not files:
            problems.append(
                f"--expected {args.expected} holds no *-expected.jsonl; nothing "
                f"was checked, which is not the same as nothing being wrong")

        seen: set[str] = set()
        answers = 0
        for path in files:
            for _case_id, blob in freeze.load_expected(path):
                answers += 1
                # A protocol answer is a whole stdout stream, so every line is a
                # response and each can carry its own error.
                for line in blob.rstrip(b"\n").split(b"\n"):
                    try:
                        payload = json.loads(line)
                    except ValueError:
                        problems.append(
                            f"{path.name}: an answer is not JSON: {line[:120]!r}")
                        continue
                    if not isinstance(payload, dict):
                        continue
                    error = payload.get("error")
                    if not isinstance(error, dict):
                        continue
                    # The same rule as `freeze.check_answers`, which is what wrote
                    # the file: a code counts as reached when a *response* failed
                    # with one. The codes inside a recovered `errors[]` array do not
                    # count -- that payload is the `ast` op reporting diagnostics it
                    # recovered from, not a request that failed -- and counting them
                    # here would make this disagree with the freeze about what the
                    # corpus reaches.
                    if error.get("kind") == "JsonataError" and error.get("code"):
                        seen.add(str(error["code"]))

        if answers and not seen:
            problems.append(
                f"read {answers} answer(s) from {args.expected} and found no error "
                f"codes at all. The corpus is supposed to reach "
                f"{len(CODES_REACHED)}, so this means the answers were read but not "
                f"understood.")
        elif seen:
            missing = sorted(set(CODES_REACHED) - seen)
            surprise = sorted(seen - set(CODES_REACHED))
            # Only meaningful over the whole corpus; one stem legitimately reaches a
            # subset, so saying "missing" about a single file would be wrong.
            if missing and args.expected.is_dir():
                problems.append(
                    f"code(s) this file says the corpus reaches but the frozen "
                    f"expectations do not contain: {missing}")
            if surprise:
                problems.append(
                    f"code(s) in the frozen expectations that this file does not "
                    f"list as reached: {surprise}")

    if args.out:
        payload = {
            "families": family_weights(counts) if counts else {},
            "modules": module_weights(),
            "release": release_weights(),
            "types": type_weights(),
            "total": budget_total(),
        }
        args.out.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n",
                            encoding="utf-8")

    print(summary(counts or None))
    if problems:
        print("\nproblems:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1 if args.check else 0
    if args.check:
        print("\ncatalog: consistent")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
