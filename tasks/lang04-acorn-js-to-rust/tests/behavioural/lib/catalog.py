def summary(counts: dict[str, int], fixtures: int) -> dict:
    """The inventory, as a dict, for the report and for `--check`."""
    weights = family_weights(counts)
    per_family = {
        family: {
            "cases": counts[family],
            "budget": round(FAMILY_BUDGETS.get(family, 0.0), 3),
            "per_case_weight": round(weights.get(family, 0.0), 6),
        }
        for family in sorted(counts)
    }
    corpus_budget = sum(
        FAMILY_BUDGETS.get(f, 0.0) for f in counts if counts[f] > 0
    )
    return {
        "corpus_cases": sum(counts.values()),
        "corpus_families": len(counts),
        "corpus_budget": round(corpus_budget, 3),
        "fixture_cases": fixtures,
        "fixture_budget": FIXTURE_BUDGET,
        "cli_cases": len(CLI_CASES),
        "cli_budget": CLI_BUDGET,
        "struct_cases": len(STRUCT_CASES),
        "guard_cases": len(GUARD_CASES),
        "mandatory_guards": sum(1 for c in GUARD_CASES if c[2]),
        "families": per_family,
        "unknown_families": unknown_families(counts),
        "missing_families": missing_families(counts),
    }


def check_catalog(counts: dict[str, int], fixtures: int) -> list[str]:
    """Everything that would make this inventory wrong.  Empty means sound."""
    problems: list[str] = []
    total = sum(counts.values())
    if total < MIN_CORPUS_CASES:
        problems.append(f"corpus has {total} cases, expected at least {MIN_CORPUS_CASES}")
    if fixtures < MIN_FIXTURE_CASES:
        problems.append(f"{fixtures} fixture cases, expected at least {MIN_FIXTURE_CASES}")
    if len(GUARD_CASES) < MIN_GUARD_CASES:
        problems.append(f"{len(GUARD_CASES)} guards, expected at least {MIN_GUARD_CASES}")
    if len(STRUCT_CASES) < MIN_STRUCT_CASES:
        problems.append(f"{len(STRUCT_CASES)} structural cases, expected at least {MIN_STRUCT_CASES}")
    if len(CLI_CASES) < MIN_CLI_CASES:
        problems.append(f"{len(CLI_CASES)} CLI cases, expected at least {MIN_CLI_CASES}")
    for name in unknown_families(counts):
        problems.append(
            f"family {name!r} is in the corpus but has no declared budget "
            f"(graded at the mean, which is a guess)"
        )
    for name in missing_families(counts):
        problems.append(
            f"family {name!r} has a budget but produced no cases: the generator "
            f"and this table disagree"
        )
    for label, ids in (("guard", [c[0] for c in GUARD_CASES]),
                       ("struct", [c[0] for c in STRUCT_CASES]),
                       ("cli", [c[0] for c in CLI_CASES])):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        if dupes:
            problems.append(f"duplicate {label} case ids: {dupes}")
    for case_id, argv, stdin_key, _weight, mode, _note in CLI_CASES:
        if stdin_key is not None and stdin_key not in CLI_SOURCES:
            problems.append(
                f"{case_id} reads stdin {stdin_key!r}, which is not in CLI_SOURCES"
            )
        if mode not in CLI_MODES:
            problems.append(
                f"{case_id} declares grading mode {mode!r}, which is not one of "
                f"{CLI_MODES}"
            )
        for arg in argv:
            if arg.startswith("<file:") and arg[6:-1] not in CLI_SOURCES:
                problems.append(
                    f"{case_id} wants file {arg}, which is not in CLI_SOURCES"
                )
    # A `status` case is a weaker comparison, so the set of them is worth
    # bounding: if a later edit quietly moved half the CLI cases into it, the
    # phase would still report a full score while measuring much less.
    status_weight = sum(c[3] for c in CLI_CASES if c[4] == "status")
    total_weight = sum(c[3] for c in CLI_CASES)
    if total_weight and status_weight > 0.2 * total_weight:
        problems.append(
            f"status-only CLI cases carry {status_weight:.1f} of {total_weight:.1f} "
            f"points; byte comparison is the point of this phase"
        )
    for name in CLI_DIRS:
        if name in CLI_SOURCES:
            problems.append(
                f"{name!r} is both a CLI directory and a CLI source; the runner "
                f"cannot create both at that path"
            )
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cases", type=Path, help="cases.json from gen_corpus.js")
    ap.add_argument("--fixtures", type=Path, help="fixtures.json from gen_corpus.js")
    ap.add_argument("--check", action="store_true", help="exit non-zero on drift")
    ap.add_argument("--out", type=Path, help="write the inventory here")
    args = ap.parse_args()

    counts: dict[str, int] = {}
    if args.cases and args.cases.is_file():
        counts = json.loads(args.cases.read_text())["families"]
    fixtures = 0
    if args.fixtures and args.fixtures.is_file():
        fixtures = len(json.loads(args.fixtures.read_text())["fixtures"])

    payload = summary(counts, fixtures)
    problems = check_catalog(counts, fixtures) if args.check else []
    payload["problems"] = problems

    text = json.dumps(payload, indent=1, sort_keys=True)
    if args.out:
        args.out.write_text(text + "\n", encoding="utf-8")
    else:
        print(text)
    if problems:
        for problem in problems:
            print(f"catalog: {problem}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
