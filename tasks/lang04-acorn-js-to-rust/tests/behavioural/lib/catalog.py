# case is 90/36 = 2.5 weight.
FIXTURE_BUDGET = 90.0

# CLI cases.  The executable is a thin wrapper over the library, so it is not
# where the difficulty is; it is where a packager's first impression is.
CLI_BUDGET = 60.0


def family_weights(counts: dict[str, int]) -> dict[str, float]:
    """Per-case weight for each family, from its budget and its size.

    A family present in the corpus but absent from the budget table is a
    generator that grew a family this file was never told about.  It gets the
    mean budget rather than zero -- silently grading something at zero is how a
    corpus ends up with cases nobody notices are unscored -- and `check_catalog`
    reports it as drift.
    """
    if not counts:
        return {}
    fallback = sum(FAMILY_BUDGETS.values()) / len(FAMILY_BUDGETS)
    out: dict[str, float] = {}
    for family, count in counts.items():
        if count <= 0:
            continue
        budget = FAMILY_BUDGETS.get(family, fallback)
        out[family] = budget / count
    return out


def unknown_families(counts: dict[str, int]) -> list[str]:
    return sorted(set(counts) - set(FAMILY_BUDGETS))


def missing_families(counts: dict[str, int]) -> list[str]:
    return sorted(set(FAMILY_BUDGETS) - set(counts))


