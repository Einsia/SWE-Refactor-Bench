"""What lang04 measures, in one inventory.

The probe corpus itself is generated by `gen_corpus.js`, because only the
JavaScript can harvest acorn's own 6,763-test suite and only the reference can
say what the answers are.  What this module owns is everything the corpus does
not: how much each family is worth, the CLI cases, the structural cases and the
audit gates.

The weighting is the part worth reading.  The corpus is deliberately lopsided --
`identifier_tables` has 2,032 cases because there are 2,032 interesting code
points to ask about, and `line_info` has 118 because there are only so many ways
to index a line.  Grading per case would make the Unicode tables worth 17 times
`get_line_info`, which is not what a reader of this task would say those two
things are worth to it.  So each family gets a budget, and its cases divide that
budget equally.  A family's importance is then a declared number in this file
rather than an accident of how many cases it was cheap to generate.
"""

