def fixture_bytes() -> bytes:
    return bytes.fromhex(FIXTURE_HEX)


def dbtotxt(raw: bytes, pgsz: int = 512, name: str = "x.db") -> str:
    """The text form ``.open --hexdb`` parses, per readHexDb() in shell.c.

    Header line giving size and page size, then for each page a ``| page N
    offset K`` line followed by that page's bytes as 16-byte rows.  readHexDb
    zero-fills its buffer first, so an all-zero row could be dropped -- it is
    kept anyway: a complete image is a fixture someone can check by eye against
    the database it came from, and a compressed one is not.
    """
    lines = [f"| size {len(raw)} pagesize {pgsz} filename {name}"]
    for pageno in range(len(raw) // pgsz):
        offset = pageno * pgsz
        lines.append(f"| page {pageno + 1} offset {offset}")
        for row in range(0, pgsz, 16):
            chunk = raw[offset + row: offset + row + 16]
            hexed = " ".join(f"{b:02x}" for b in chunk)
            ascii_ = "".join(chr(b) if 32 <= b < 127 else "." for b in chunk)
            lines.append(f"|   {row}: {hexed}  {ascii_}")
    lines.append(f"| end {name}")
    return "\n".join(lines) + "\n"


def hexdb_text() -> str:
    return dbtotxt(fixture_bytes())
